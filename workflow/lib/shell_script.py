"""Wrap a rule's command so it is first written to a standalone shell script, then executed.

Usage inside a rule:

    params:
        script=script_path("01_Repeat", "01_edta"),
    log:
        out=log_path("01_Repeat", "01_edta", "out"),
        err=log_path("01_Repeat", "01_edta", "err"),
    shell:
        SH('''
        EDTA.pl --genome {input.genome} --threads {threads}
        ''', env="repeat", versions="EDTA.pl -h 2>&1 | head -n 3")

Snakemake formats the whole returned string, so the {placeholders} are expanded before the
heredoc is written. The heredoc delimiter is quoted, so shell variables and $(...) inside the
command are written literally and only evaluated when the script itself runs. The finished
script can therefore be re-run by hand with `bash <script>` (after activating the env named in
its header).
"""

import textwrap

HEREDOC = "__ANNOTATION_PIPELINE_EOF__"


def _escape_braces(s):
    return s.replace("{", "{{").replace("}", "}}")


def SH(cmd, env=None, versions=None, workdir=None):
    """Return a Snakemake shell template that writes `cmd` to {params.script} and runs it.

    cmd      -- command template (Snakemake placeholders allowed).
    env      -- name of the workflow/envs/<env>.yaml the command needs (recorded in the header).
    versions -- optional command whose output is appended to <step>/logs/versions/<script>.txt.
    workdir  -- optional directory (Snakemake placeholder allowed) to cd into before running.
    """
    body = cmd.strip("\n")
    first, _, rest = body.partition("\n")
    # dedent the first line and the remaining lines separately, so a command that starts with a
    # non-indented prefix (e.g. PY("x.py") + """ ... """) is dedented correctly as well
    body = first.strip() + ("\n" + textwrap.dedent(rest) if rest else "")
    env_note = f"workflow/envs/{env}.yaml" if env else "none"

    lines = [
        "mkdir -p \"$(dirname {params.script})\" \"$(dirname {log.out})\" \"$(dirname {log.out})/versions\"",
        # Header: expanded now (unquoted), records env and when it was generated.
        "{{",
        "  echo '#!/usr/bin/env bash'",
        "  echo '# Generated by the Concordia Snakemake workflow (rule: {rule})'",
        "  echo \"# Generated at: $(date '+%Y-%m-%d %H:%M:%S')\"",
        f"  echo '# Required environment: {env_note}'",
        "  echo \"# CONDA_PREFIX when generated: ${{CONDA_PREFIX:-none}}\"",
        "  echo '# Re-run by hand: activate the environment above, then: bash <this script>'",
        "  echo 'set -euo pipefail'",
        "  echo 'echo \"[start] $(date \"+%Y-%m-%d %H:%M:%S\") rule={rule}\"'",
        "}} > {params.script}",
    ]
    if versions:
        lines += [
            f"cat >> {{params.script}} <<'{HEREDOC}'",
            "( " + _escape_braces(versions) + " ) > \"$(dirname {log.out})/versions/$(basename {params.script} .sh).txt\" 2>&1 || true",
            HEREDOC,
        ]
    if workdir:
        lines += [
            f"cat >> {{params.script}} <<'{HEREDOC}'",
            "mkdir -p " + workdir + " && cd " + workdir,
            HEREDOC,
        ]
    lines += [
        f"cat >> {{params.script}} <<'{HEREDOC}'",
        body,
        "echo \"[end] $(date \"+%Y-%m-%d %H:%M:%S\")\"",
        HEREDOC,
        "chmod +x {params.script}",
        "bash {params.script} > {log.out} 2> {log.err}",
    ]
    return "\n".join(lines) + "\n"
